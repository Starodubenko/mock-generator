export const generateHelp = (contour: string): string => `# Генерация документов

Задание создаёт синтетические документы **той же формы**, что эталон, и отдаёт их соседнему микросервису. Сервис сам в поисковый кластер не пишет.

Публикация идёт в контур \`${contour}\`. Метку времени пачки сервис ставит сам в часовом поясе этого контура.

## Перед запуском

- На контуре должна быть **активированная** версия профиля. В селекторе можно взять рабочую или конкретную версию.
- Если версий ещё нет, форма скрыта. Кнопка **Обучить** открывает вкладку обучения.
- Контур — из разрешённого списка. Прод-цель и прод-контур отклоняются до первой публикации.
- Не запускайте генерацию в индекс, с которого только что учили: учиться на собственной синтетике нельзя.

## Поля формы

- **Версия профиля** — селектор обученных версий: идентификатор и алиас, если его задали после обучения. «Рабочая версия контура» берёт активную. Смена пункта обновляет схему полей.
- **Ключ вариации** — вместе с заданием, версией и контуром фиксирует документ. Одинаковые входные данные дают одинаковый документ. Другой ключ даёт другую партию значений.
- **Количество** — сколько документов запросить. Если пути массивов пустые, столько корневых объектов уйдёт в черновик. Если путь указан, столько элементов будет в этом массиве.
- **Пути массивов** — например \`hits.hits\`. Тогда генерируется **один объект** модели, а список — только в указанных массивах. Пусто — вся модель как массив документов. Повтор пути не добавляется. Рядом с полями \`array\` в схеме есть кнопка быстрого добавления; и добавление, и удаление, и запуск задания спрашивают подтверждение.
- **Момент запуска** — сервис ставит его сам в поясе контура. На форме этого поля нет.
- **Схема документа** — то же дерево, что на карточке версии. Boolean, enum и даты — выпадающие списки или поле. Пустой выбор оставляет значения как в профиле. Даты без выбора попадают в календарный день запуска. Иконка **Развернуть** открывает схему на весь экран; в шапке — текущие версия, ключ и количество, плюс **Закрыть** и **Запустить задание**.

Тип документа приходит с карточки на главной (**Сгенерировать**) или остаётся типом по умолчанию, если открыть вкладку без типа. В одно задание не подмешиваются чужие типы.

## Как проходит задание

1. Сервис принимает задание и сразу показывает карточку.
2. Сначала собирается **черновик** — документы ещё не уходят на стенд.
3. На карточке нажмите **Посмотреть данные**, проверьте пачку и **Опубликовать**. Перед заливкой сервис спросит подтверждение и **целевой индекс** — куда соседний микросервис положит синтетику. Не прод и не индекс, с которого учили этот профиль.
4. После публикации уходит **пробная пачка** (по умолчанию до 100 документов, не больше запрошенного числа).
5. Индекс обновляется, затем выполняются золотые запросы интерфейса.
6. Любой провал пробы — полная заливка не стартует, пробные документы снимаются.
7. Успех пробы открывает полную публикацию. Сомнительный документ **не публикуется**.

Задание навсегда связано с четвёркой: версия, ключ вариации, идентификатор задания, контур. Повтор того же задания пишет те же идентификаторы (upsert). Новый прогон — новое задание.

## После отправки

Браузер перейдёт на карточку задания. Обновление формы второе задание не создаёт.

Типичные отказы на этой странице: нет рабочей версии, контур запрещён, цель похожа на прод, слишком много активных заданий контура, источник или маппинг несовместимы.

> В документах не будет боевых фамилий, адресов и внутренних идентификаторов корпуса. Идентификаторы выводятся из задания и номера документа.
`;
