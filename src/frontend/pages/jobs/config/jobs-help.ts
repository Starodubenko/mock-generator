export const jobsHelp = (contour: string): string => `# Список заданий

Здесь все задания **текущего контура**: обучение профиля и генерация. Тел документов в списке нет — только дата создания, идентификатор, вид, тип и состояние.

Таблица ранжируется по дате создания (часовой пояс контура): самые свежие на первой странице. Дальше — пагинация.

## Как читать строку

- **Обучение** — снимок корпуса и сбор версии. После успеха откройте версию и решите, активировать ли её.
- **Генерация** — сначала черновик и просмотр пачки, затем публикация на стенд: пробная пачка, золотые запросы и полная заливка.

Состояния по порядку:

1. **принято** — задание в очереди;
2. **профилирование** / **профиль готов** — для обучения;
3. **активация** — редкий служебный шаг;
4. **черновик** — пачка сгенерирована, на стенд ещё не ушла;
5. **пробная пачка** — canary до полной заливки;
6. **публикация** — идёт полная выгрузка;
7. **успех**, **ошибка** или **отменено** — финал, назад в работу задание не возвращается.

## Что делать

- Нажмите идентификатор — откроется карточка со счётчиками, причиной отказа и карантином.
- Новое задание генерации — вкладка [Генерация](/jobs/new?contour=${contour}) или кнопка на главной.
- Список всегда фильтруется контуром из шапки. Переключили контур — видите другие задания.

## Пустой список

Это нормально для свежего стенда. Сначала обучите и активируйте профиль, затем запустите генерацию. Если контуров нет в разрешённом списке, задания с публикацией не создаются.
`;
