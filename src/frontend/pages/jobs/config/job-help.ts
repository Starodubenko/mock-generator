export const jobHelp = (
  jobId: string,
  kind = 'generate',
): string => `# Карточка задания

Пока состояние не финальное, карточка **обновляется сама** по каналу пульта. Если канал недоступен, блок статуса опрашивается каждые 3 секунды. Шапка и контур не перерисовываются. Опрос и канал останавливаются на «успех», «ошибка» или «отменено». «Черновик» — ещё не финал: можно смотреть пачку и публиковать.

${
  kind === 'train'
    ? `## Обучение

Это задание **не публикует** документы. Ноль в счётчике публикации — ожидаемый итог. После успеха откроется вкладка версий и окно алиаса. Активируйте версию отдельно, затем запускайте генерацию.`
    : `## Генерация

Сначала сервис только собирает черновик. Нажмите **Посмотреть данные**, проверьте пачку и **Опубликовать**. **Сохранить в моки** открывает выбор группы и эндпоинта: подтвердите, и JSON станет ответом. Перед отправкой на стенд сервис спросит подтверждение и целевой индекс. Затем уйдёт пробная пачка, золотые запросы и полная заливка.`
}

## Счётчики

- **Опубликовано** — сколько документов соседний микросервис принял в задании генерации. Для обучения всегда 0.
- **В карантине** — сколько отклонено. Откройте [карантин](/jobs/${jobId}/quarantine): там идентификатор и причина, без тела.

Сомнительный документ в индекс не попадает. Готовность задания — это успешные золотые запросы после обновления индекса, а не «сколько сообщений ушло».

## Отмена

Кнопка **Отменить задание** видна только до финала. Сервис сначала спросит подтверждение. После отмены карточка показывает «отменено». Уже записанные документы остаются в индексе как есть.

## Если задание упало

Причина отказа — из закрытого списка, на русском. Частые случаи:

- пробная пачка или золотые запросы не прошли;
- слишком много отказов соседнего микросервиса (ядовитые ответы);
- не удалось набрать пачку с инвариантами;
- цель или контур запрещены;
- ссылка на документ вне этого задания;
- конфликт типов или маппинга.

Исправьте входные данные и запустите **новое** задание. Старое из финала не перезапускается. Чтобы повторить те же идентификаторы, нужны тот же ключ вариации и тот же идентификатор задания — обычная форма создаёт новое.

## Связанные типы

Одно задание — один сценарий. Ссылка на документ вне этого задания документ не выпускает.
`;
