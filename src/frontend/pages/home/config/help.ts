export const homeHelp = (contour: string): string => `# Пульт оператора

Это рабочий стол сервиса: здесь видно, **в каком контуре вы работаете** и какие **типы документов** уже заведены. Тел документов — ни корпуса, ни синтетики — на пульте нет и не будет.

## С чего начать

1. В шапке проверьте контур. Все ссылки и формы дальше пойдут с ним.
2. Тип заводят на вкладке [Типы документов](/document-types?contour=${contour}).
3. Если у типа нет текущей версии — откройте [Обучение](/profiles/document?contour=${contour}) и приложите эталонные файлы вручную.
4. В блоке типа нажмите **Профили**, задайте алиас и **активируйте** карточку. Обучение само по себе рабочую версию не меняет.
5. Когда версия активна, на карточке нажмите **Сгенерировать** — форма откроется уже с этой рабочей версией. Либо откройте [Генерацию](/jobs/new?contour=${contour}) сами.
6. Ход задания смотрите в [списке](/jobs?contour=${contour}) и на карточке. Статус обновляется сам, пока задание не завершится.

Над списком типов — ссылки **Обучить профиль**, **Новое задание генерации** и **Список заданий**.

## Контур

Контур — это стенд и его часовой пояс. Список берётся из разрешённых контуров сервиса.

- Пустой список контуров означает: **обучать и публиковать нельзя**.
- Прод-контур сервис отклонит до первой публикации.
- Часовой пояс контура нужен, чтобы сервис сам проставил момент запуска: документы попадают в фильтр «сегодня» на этом стенде.

Переключить контур можно селектором в шапке.

## Типы документов

На главной только те типы, которые уже созданы. На плашке — текущая версия этого контура или пометка, что профиля ещё нет.

Кнопка **Обучить** открывает вкладку обучения уже с этим типом. **Профили** раскрывает тип на вкладке типов документов. **Сгенерировать** открывает форму генерации с типом карточки и её текущей версией, если версия уже активна.

## Что видно, а чего нет

На пульте можно увидеть: контур, тип, идентификатор версии, состояние задания, счётчики, причину отказа, идентификаторы карантина. Для генерации кнопка «Посмотреть данные» открывает синтетический черновик.

Не показывается: тело эталонного корпуса, платформенный токен, адрес соседнего микросервиса. Так и задумано — оператор управляет процессом, а не читает чужие документы.

## Если что-то неясно

- Нет рабочей версии — сначала обучение, потом активация, и только затем генерация.
- Ошибка на форме остаётся на той же странице: исправьте поля и отправьте снова.
- Успешная отправка уводит на карточку задания. Повторное обновление страницы второе задание не создаёт.
`;
