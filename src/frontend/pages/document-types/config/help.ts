export const documentTypesHelp = (contour: string): string => `# Типы документов

Каталог типов контура \`${contour}\`. Тип заводят здесь, затем обучают профиль. Версии (профили) лежат **внутри** типа: раскройте блок.

## Как добавить тип

Кнопка **Добавить тип** открывает форму. Идентификатор — латиница, цифры и дефис, начинается с буквы. Пример: \`document\`. После создания тип появляется на главной и в селекторе обучения.

## Профили внутри типа

Под типом — версии этого контура. Идентификатор версии — хэш содержимого.

- **текущий** — рабочая версия генерации на этом контуре.
- **Активировать** нетекущую версию — после подтверждения.
- **Открыть** — схема, дифф, активация и откат.
- **Удалить** нетекущую версию — после подтверждения.

Если профилей ещё нет, внутри блока кнопка **Обучить**.

## Удаление типа

Удаление типа снимает **все его профили** с этого процесса. Соседний микросервис и поисковый кластер отсюда не чистятся. Подтверждение спрашивает отдельно.

Обучение само по себе рабочую версию не меняет: сначала активируйте карточку профиля.
`;
