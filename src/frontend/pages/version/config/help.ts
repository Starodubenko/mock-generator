export const versionHelp = (contour: string): string => `# Карточка версии

Версия — это **канонический снимок профиля**. Идентификатор считается по содержимому, версия не переписывается. Смена конфигурации сервиса старые версии не меняет.

Активация и откат действуют на контур \`${contour}\`. У другого контура свой журнал рабочей версии.

## Что смотреть

- **Схема документа.** Дерево полей как у эталона: вложенные объекты внутри скобок, тип каждого поля цветом как в Swagger. После \`:\` анализатор показывает все встреченные типы через \` | \`, например \`date | null\`. Массив показывается как \`array[string]\`, \`array[object]\` и так же по остальным классам элемента. \`array[object]\` раскрывается как обычный объект: поля элемента внутри квадратных скобок. Путь с двумя типами в одном снимке получает \`rejected\`. **Редактировать** рядом с активацией открывает имена и типы полей. Если выбран enum — справа та же кнопка **Изменить**. **Добавить поле** открывает модалку с именем и типом; для enum там тоже есть **Изменить**. Сохранение не переписывает снимок: сервис предлагает новую версию. В модалке можно включить **Сделать активной новую версию**. **Отменить** с несохранёнными правками спрашивает подтверждение. В обычном виде блок сворачивается шевроном. Иконка **Развернуть** открывает схему и связи на весь экран: слева дерево, справа настройки связей.
- **Настройки связей.** После обучения здесь базовые равенства id, parent/child и порядок дат. Блок тоже сворачивается шевроном. Вопросик у вида связи поясняет, что синтезатор делает с этими путями. **Добавить связь** / **Удалить** доступны в режиме правки. Сохранение создаёт новую версию; синтезатор читает сохранённый набор.
- **Дифф** к уже активированной версии: чипы показывают число. Наведение на **Удержано гистерезисом** поясняет порог. Клик по чипу с числом открывает список путей (добавлено, удалено, смена типа, удержано гистерезисом).
- **Отклонённые пути.** Если их больше нуля, эту версию активировать нельзя.

Гистерезис гасит мелкие колебания «поле есть / поля нет» между соседними обучениями, если тип тот же и порог не пробит. Такое колебание само по себе активацию не блокирует.

## Редактирование схемы

Версия иммутабельна. Смена имени, класса пути, домена enum или добавление поля не правит текущий идентификатор — получается новая версия. Переименование пишется как alias (со старого пути на новый). По умолчанию рабочая версия контура не переключается: это та же «явная политика типа», что в правилах активации. Тумблер в модалке сохранения — отдельный шаг активации и сработает только если в новой версии нет путей \`rejected\`.

## Активация

Нажмите **Активировать**, когда дифф понятен и отклонённых путей нет. Перед сменой рабочей версии сервис спросит подтверждение.

- Рабочая версия пишется в журнал **одна на пару** «тип документа + контур».
- Предыдущая рабочая остаётся в хранилище — её можно вернуть откатом.
- Смена типа пути блокирует активацию, пока новое обучение или явная политика не выведет путь из \`rejected\`.
- Отказ оставляет вас на этой странице: видна причина и **прежняя** рабочая версия. Генерация продолжает идти по ней.

## Откат

Кнопка отката появляется, если есть другая активная версия. Это повторная активация старой версии — но только если её маппинг индекса всё ещё совместим. Откат тоже подтверждается в модалке.

## Чего здесь нет

Тел документов и сырых частот свободного текста нет. Смотрите только метаданные путей и решение: активировать, подождать нового обучения или откатиться.
`;
