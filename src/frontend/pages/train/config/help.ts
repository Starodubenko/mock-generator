export const trainHelp = (contour: string): string => `# Обучение профиля

Обучение строится **только по файлам, которые вы прикладываете вручную**. Сервис не ходит в индекс и не скачивает эталон сам.

Сейчас выбран контур \`${contour}\`. Он уйдёт в задание вместе с формой.

## Тип документа

Селектор **Тип документа** берётся из адреса страницы: /profiles/тип. Кнопка «Обучить» на плашке типа на главной открывает эту вкладку уже с нужным типом. Смена селектора перезагружает форму выбранного типа и не отправляет корпус.

## Что приложить

- Перетащите файлы в зону на форме или нажмите на неё.
- Один или несколько файлов \`.json\`, \`.ndjson\` или \`.jsonl\`.
- JSON — массив объектов, один объект или выгрузка _search целиком (took, _shards, hits). Оболочку OpenSearch сервис не срезает: схема повторяет файл.
- NDJSON — один объект на строку.
- До 10 файлов, до 8 МБ каждый.
- Поля размера выборки, alias и кнопка обучения появятся, когда в зоне будет хотя бы один файл. Сама зона тогда скрывается: справа от имени файла — «Удалить».

Тела файлов на пульте не показываются и после ошибки не возвращаются: браузер не даёт подставить файл обратно, приложите его снова.

## Когда нажимать «Запустить обучение»

Когда эталон изменился или контур поднимаете впервые. Параллельное второе обучение того же профиля на этом контуре не стартует.

## Остальные поля

- **Размер выборки** — сколько документов взять из приложенных файлов. Выгрузка _search — один JSON-объект, но к минимуму для активации считается число hits. Если выборка меньше минимума, версия сохранится, но **активировать её нельзя**.
- **С какого пути / на какой путь** — необязательный alias: переименовать путь в профиле, не меняя файлы. Пример: source.kind → kind. Вложенный путь пишется через точку: nested.code.

## Что делает сервис после отправки

1. Читает только приложенные файлы в памяти. На диск и в индекс корпус не пишется.
2. Берёт не больше указанного размера выборки.
3. Строит дерево путей и отчёт.
4. Сверяет типы с маппингом целевого синтетического индекса.
5. Считает дифф с уже активированной версией этого контура.
6. Сохраняет новую версию. **Не активирует.**

Браузер уходит на вкладку **Типы документов**, блок этого типа. Когда обучение закончится, откроется окно алиаса. Обновление страницы второе задание не создаёт.

## После обучения

На вкладке **Типы документов** раскройте тип, задайте алиас, откройте карточку: схема, дифф, **Активировать** / **Откатить**. Неактивную версию можно удалить с подтверждением.

> Активация — отдельный шаг. Пока вы её не подтвердили, генерация пишет по прежней рабочей версии.

## Типичные отказы

- Файлы не приложены или в них нет объектов — корпус пуст.
- Файл не JSON и не NDJSON.
- В выборке смешаны типы документов.
- Выборка меньше минимума — версия есть, активация запрещена.
- Контур не из разрешённого списка.
- Для этого профиля уже идёт обучение.

Не прикладывайте выгрузку, которую этот сервис уже сгенерировал: профиль не должен учиться на собственной синтетике.
`;
